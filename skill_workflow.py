"""Local evidence selection and narrow qualitative safeguards."""
import re
import math


def select_evidence(records, skill):
    if skill == 'anomaly-detection':
        return [r for r in records if r.get('category') == 'Financial Anomaly']
    return list(records)


def anomaly_rows(records):
    rows = []
    for r in records:
        if r.get('category') != 'Financial Anomaly':
            continue
        v = r['values']
        value = v.get('value')
        if not isinstance(value, (int, float)) or not math.isfinite(value):
            continue
        margin = v.get('category') == 'Margin Compression'
        rows.append({'Period': v.get('period'), 'Anomaly': v.get('category'),
                     'Severity': v.get('severity'), 'Change': f'{value:+.2f} pp' if margin else f'{value:+.2%}',
                     'Evidence': r['evidence_id']})
    return sorted(rows, key=lambda r: r['Severity'] != 'High')


def qualitative_diagnostic(observation, records):
    # No comparable annual growth evidence is currently generated by this application.
    if re.search(r'\b(?:annual|yearly|year.over.year|full.year|year.on.year|yoy)\b', observation, re.I) and re.search(r'\b(?:growth|grew|grown|increas\w*|declin\w*|fell|rose|improv\w*|decreas\w*)\b', observation, re.I):
        return 'Annual comparison claim requires comparable annual evidence'
    if records and all(r.get('category') == 'Financial Anomaly' for r in records) and re.search(r'\b(?:without|no|missing|absent|unavailable|not provided)\b.{0,45}\b(?:data|information|figures|metrics)\b', observation, re.I):
        return 'Flag-only evidence cannot establish missing underlying data'
    return None


def anomaly_commentary_context(records):
    """Only qualitative flag metadata is needed for anomaly commentary."""
    return [{'evidence_id': r['evidence_id'], 'category': r['values']['category'],
             'period': r['values']['period'], 'severity': r['values']['severity']}
            for r in records]


def mask_cited_anomaly_dates(text, records):
    """Allow exact cited month-year labels, never standalone financial numbers."""
    for r in records:
        if r.get('category') != 'Financial Anomaly':
            continue
        period = r['values'].get('period', '')
        if isinstance(period, str) and re.fullmatch(r'(?:January|February|March|April|May|June|July|August|September|October|November|December) [0-9]{4}', period):
            text = re.sub(r'(?<![\w.,$€£%])' + re.escape(period) + r'(?![\w%]|[.,]\d)', period.split()[0], text)
    return text


def executive_commentary_context(records):
    """Compact projection; full evidence remains available locally."""
    fields = {'revenue','cogs','gross_profit','gross_margin','revenue_share',
              'revenue_growth','margin_change_pp','budget','budget_variance',
              'budget_variance_pct','budget_revenue','actual_revenue'}
    out = []
    for r in records:
        if r.get('category') == 'Financial Anomaly':
            out.extend(anomaly_commentary_context([r]))
        else:
            values = {k: v for k,v in r['values'].items() if k in fields}
            out.append(dict(evidence_id=r['evidence_id'], title=r['title'], values=values or r['values']))
    return out


def executive_risks(records):
    """Calculate report highlights from the selected scope, not model prose."""
    def group(prefix, field):
        return [r for r in records if r['title'].startswith(prefix) and isinstance(r['values'].get(field),(int,float)) and math.isfinite(r['values'][field])]
    def name(r): return r['title'].split(':',1)[-1].strip()
    def row(priority, risk, metric, action, rs):
        return {'Priority':priority,'Finding':risk,'Calculated metric':metric,'Proposed review':action,'Evidence':' '.join('['+r['evidence_id']+']' for r in rs)}
    rows=[]
    for r in sorted(group('Segment:', 'gross_margin'),key=lambda r:r['values']['gross_margin']):
        if r['values']['gross_margin'] < 0:
            rows.append(row('High',name(r)+' negative gross margin',f"{r['values']['gross_margin']:.2%}",'Review pricing, discounts and costs.',[r]))
    declines=[r for r in records if r.get('category')=='Financial Anomaly' and r['values'].get('category')=='Revenue Decline' and isinstance(r['values'].get('value'),(int,float)) and math.isfinite(r['values']['value'])]
    if declines:
        r=min(declines,key=lambda r:r['values']['value'])
        rows.append(row('High' if r['values'].get('severity')=='High' else 'Medium',r['values']['period']+' revenue decline',f"{r['values']['value']:+.2%}",'Investigate monthly revenue drivers.',[r]))
    shares=sorted(group('Segment:', 'revenue_share'),key=lambda r:r['values']['revenue_share'],reverse=True)[:2]
    if len(shares)==2:
        share=sum(r['values']['revenue_share'] for r in shares)
        rows.append(row('High' if share>=.75 else 'Medium',' and '.join(map(name,shares))+' revenue exposure',f'{share:.2%}','Assess concentration exposure and resilience.',shares))
    products=group('Product:', 'gross_margin')
    if products:
        r=min(products,key=lambda r:r['values']['gross_margin'])
        rows.append(row('Medium',name(r)+' lowest product gross margin',f"{r['values']['gross_margin']:.2%}",'Review product pricing and costs.',[r]))
    return sorted(rows,key=lambda r:r['Priority']!='High')
